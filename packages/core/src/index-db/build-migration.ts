import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('./', import.meta.url);
const journal = JSON.parse(
  readFileSync(new URL('migrations/meta/_journal.json', root), 'utf8'),
) as {
  entries: { tag: string }[];
};
const sql = journal.entries
  .map(({ tag }) =>
    readFileSync(new URL(`migrations/${tag}.sql`, root), 'utf8'),
  )
  .join('\n');
// Composite primary keys retain SQLite rowids; FTS uses the actual rowid, never uuid.
const fts = `
CREATE VIRTUAL TABLE messages_fts USING fts5(text, content='messages', content_rowid='rowid');
CREATE TRIGGER messages_ai AFTER INSERT ON messages BEGIN INSERT INTO messages_fts(rowid,text) VALUES(new.rowid,new.text); END;
CREATE TRIGGER messages_ad AFTER DELETE ON messages BEGIN INSERT INTO messages_fts(messages_fts,rowid,text) VALUES('delete',old.rowid,old.text); END;
CREATE TRIGGER messages_au AFTER UPDATE ON messages BEGIN INSERT INTO messages_fts(messages_fts,rowid,text) VALUES('delete',old.rowid,old.text); INSERT INTO messages_fts(rowid,text) VALUES(new.rowid,new.text); END;
`;
writeFileSync(
  fileURLToPath(new URL('migration.ts', root)),
  `// Generated by db:generate; do not edit. Bundled for tsc-only distribution.\nexport const schemaVersion = ${JSON.stringify(journal.entries.at(-1)!.tag)};\nexport const migrationSql = ${JSON.stringify(sql + fts)};\n`,
);
