import { z } from 'zod';
import type {
  CommandReceipt,
  ControlRuns,
  DecisionBody,
  NewProjectBody,
  NewSessionBody,
  PermissionMode,
  SessionLabels,
  WorkspaceBrowse,
  WorkspaceRoots,
} from '@c9view/api';
import { get, machinePath } from '../api.js';

const trustSchema = z.object({
  path: z.string(),
  fingerprint: z.string(),
  hooks: z.array(z.string()),
  mcpServers: z.array(z.string()),
  allowRules: z.array(z.string()),
  plugins: z.array(z.string()),
  hasClaudeMd: z.boolean(),
});
export const receiptSchema = z.object({
  clientRequestId: z.string(),
  bootId: z.string(),
  operation: z.string(),
  status: z.enum(['accepted', 'running', 'done', 'failed', 'cloning', 'ready']),
  runId: z.string().optional(),
  sessionId: z.string().optional(),
  projectId: z.string().optional(),
  error: z.string().optional(),
});
const rootsSchema = z.object({ roots: z.array(z.string()) });
const browseSchema = z.object({
  path: z.string().optional(),
  parent: z.string().optional(),
  entries: z.array(z.object({ name: z.string(), path: z.string() })),
  truncated: z.boolean(),
});
const labelsSchema = z.object({
  labels: z.array(
    z.object({
      projectId: z.string(),
      sessionId: z.string(),
      label: z.string(),
    }),
  ),
});
const baseRequest = {
  requestId: z.string(),
  runId: z.string(),
  sessionId: z.string(),
  createdAt: z.string(),
  expiresAt: z.string(),
};
export const runsSchema = z.object({
  runs: z.array(
    z.object({
      runId: z.string(),
      sessionId: z.string(),
      projectId: z.string(),
      state: z.enum([
        'starting',
        'running',
        'waiting',
        'idle',
        'ended',
        'failed',
      ]),
      mode: z.enum(['default', 'acceptEdits', 'plan', 'bypassPermissions']),
      queued: z.number().int().nonnegative(),
      costUsd: z.number().optional(),
      error: z.string().optional(),
      startedAt: z.string(),
      ownedByC9view: z.literal(true),
    }),
  ),
  requests: z.array(
    z.discriminatedUnion('kind', [
      z.object({
        ...baseRequest,
        kind: z.literal('permission'),
        toolName: z.string(),
        summary: z.string(),
      }),
      z.object({
        ...baseRequest,
        kind: z.literal('question'),
        questions: z.array(
          z.object({
            question: z.string(),
            header: z.string(),
            options: z.array(
              z.object({ label: z.string(), description: z.string() }),
            ),
            multiSelect: z.boolean(),
          }),
        ),
      }),
    ]),
  ),
});
const errorSchema = z.object({
  error: z.string(),
  reason: z.string().optional(),
  trust: trustSchema.optional(),
});
export type ControlFailureKind =
  'conflict' | 'rate-limit' | 'bad-request' | 'uncertain' | 'http';
export class ControlError extends Error {
  constructor(
    message: string,
    public kind: ControlFailureKind,
    public clientRequestId: string,
    public status?: number,
    public reason?: string,
    public trust?: z.infer<typeof trustSchema>,
  ) {
    super(message);
  }
}
export const unknownOutcome =
  'This command may or may not have run. Check the session before sending again.';
// Boot identity belongs to the node (R3), captured with the command, never generated by the browser.
export function controlApi(machineId: string, bootId: string) {
  const receipt = async (
    id: string,
    signal?: AbortSignal,
  ): Promise<CommandReceipt> =>
    receiptSchema.parse(
      await get<unknown>(
        machinePath(machineId, `/control/receipts/${encodeURIComponent(id)}`),
        signal,
      ),
    ) as CommandReceipt;
  // A POST runs once: timeout, gateway failure or an unreadable receipt may hide
  // a committed command. Recover only with receipt GETs; never replay it.
  // A manual resend after a clean failure is a new command with a fresh ID.
  async function post(path: string, body: object) {
    const clientRequestId = crypto.randomUUID();
    let response: Response;
    try {
      response = await fetch(`/api${machinePath(machineId, path)}`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'X-C9view-Control': '1',
          'X-C9view-Boot-Id': bootId,
        },
        body: JSON.stringify({ ...body, clientRequestId }),
        signal: AbortSignal.timeout(30_000),
      });
    } catch {
      throw new ControlError(
        'This may have been sent',
        'uncertain',
        clientRequestId,
      );
    }
    if ([503, 504, 408].includes(response.status))
      throw new ControlError(
        'This may have been sent',
        'uncertain',
        clientRequestId,
        response.status,
      );
    let raw: unknown;
    try {
      raw = await response.json();
    } catch {
      throw new ControlError(
        'This may have been sent',
        'uncertain',
        clientRequestId,
        response.status,
      );
    }
    if (response.ok) {
      const parsed = receiptSchema.safeParse(raw);
      if (!parsed.success)
        throw new ControlError(
          'This may have been sent',
          'uncertain',
          clientRequestId,
          response.status,
        );
      return parsed.data as CommandReceipt;
    }
    const parsed = errorSchema.safeParse(raw);
    const failure = parsed.success
      ? parsed.data
      : { error: `Request failed (${response.status})` };
    if (response.status === 401)
      window.dispatchEvent(
        new CustomEvent('c9view:login', { detail: 'token' }),
      );
    throw new ControlError(
      failure.reason === 'unknown-outcome' ? unknownOutcome : failure.error,
      response.status === 409
        ? 'conflict'
        : response.status === 429
          ? 'rate-limit'
          : response.status === 400
            ? 'bad-request'
            : 'http',
      clientRequestId,
      response.status,
      failure.reason,
      failure.trust,
    );
  }
  const session = (projectId: string, sessionId: string) =>
    `/projects/${encodeURIComponent(projectId)}/sessions/${encodeURIComponent(sessionId)}`;
  return {
    receipt,
    runs: async (signal?: AbortSignal): Promise<ControlRuns> =>
      runsSchema.parse(
        await get<unknown>(machinePath(machineId, '/control/runs'), signal),
      ) as ControlRuns,
    reply: (projectId: string, sessionId: string, text: string, fork = false) =>
      post(`${session(projectId, sessionId)}/messages`, {
        text,
        ...(fork ? { fork: true } : {}),
      }),
    newSession: (
      projectId: string,
      body: Omit<NewSessionBody, 'clientRequestId'>,
    ) => post(`/projects/${encodeURIComponent(projectId)}/sessions`, body),
    decide: (
      requestId: string,
      decision: Omit<DecisionBody, 'clientRequestId'>,
    ) => post(`/control/requests/${encodeURIComponent(requestId)}`, decision),
    interrupt: (runId: string) =>
      post(`/control/runs/${encodeURIComponent(runId)}/interrupt`, {}),
    stop: (runId: string) =>
      post(`/control/runs/${encodeURIComponent(runId)}/stop`, {}),
    mode: (runId: string, mode: PermissionMode) =>
      post(`/control/runs/${encodeURIComponent(runId)}/mode`, { mode }),
    workspaceRoots: async (signal?: AbortSignal): Promise<WorkspaceRoots> =>
      rootsSchema.parse(
        await get<unknown>(machinePath(machineId, '/workspace/roots'), signal),
      ),
    browse: async (
      path: string | undefined,
      hidden: boolean,
      signal?: AbortSignal,
    ): Promise<WorkspaceBrowse> => {
      const query = new URLSearchParams();
      if (path) query.set('path', path);
      if (hidden) query.set('hidden', '1');
      const text = query.toString();
      return browseSchema.parse(
        await get<unknown>(
          machinePath(machineId, `/workspace/browse${text ? `?${text}` : ''}`),
          signal,
        ),
      ) as WorkspaceBrowse;
    },
    newProject: (body: Omit<NewProjectBody, 'clientRequestId'>) =>
      post('/projects', body),
    labels: async (signal?: AbortSignal): Promise<SessionLabels> =>
      labelsSchema.parse(
        await get<unknown>(machinePath(machineId, '/labels'), signal),
      ),
    label: (projectId: string, sessionId: string, label: string) =>
      post(`${session(projectId, sessionId)}/label`, { label }),
    trust: (path: string, fingerprint: string) =>
      post('/projects/trust', { path, fingerprint }),
  };
}
